
import io
import html

from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer
)


def generate_pdf_report(analysis):

    buffer = io.BytesIO()

    document = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=20 * mm,
        leftMargin=20 * mm,
        topMargin=20 * mm,
        bottomMargin=20 * mm
    )

    styles = getSampleStyleSheet()

    story = []

    story.append(
        Paragraph(
            "AI CV Matching Report",
            styles["Title"]
        )
    )

    story.append(Spacer(1, 15))

    story.append(
        Paragraph(
            "Generated by AI Job Description and CV Matcher",
            styles["Normal"]
        )
    )

    story.append(Spacer(1, 20))

    safe_analysis = html.escape(str(analysis))
    formatted_analysis = safe_analysis.replace("\n", "<br/>")

    story.append(
        Paragraph(
            formatted_analysis,
            styles["BodyText"]
        )
    )

    document.build(story)

    buffer.seek(0)

    return buffer.getvalue()
